export function renderReviewDeskResultBlocks(result: ReviewDeskResult, generatedAt: Date): NotionAppendBlock[] {
  const review = result.review;
  const evidence = result.evidence;

  return [
    { type: "divider", divider: {} },
    heading(2, `Review + Iteration Desk: ${review.verdict}`),
    ...paragraph(`Generated by chief-of-staff-agent-office Review Desk at ${generatedAt.toISOString()}.`),
    ...paragraph(result.finalApprovalWarning),
    heading(3, "Pull Request"),
    ...paragraph(`${evidence.pullRequest.repository}#${evidence.pullRequest.pullRequestNumber}: ${evidence.pullRequest.url}`),
    heading(3, "Review Summary"),
    ...paragraph(review.summary),
    ...listSection(
      "Deterministic Gates",
      evidence.policyFindings.map((finding) => `${finding.severity}: ${finding.message}`),
    ),
    ...listSection("Risks", review.risks),
    ...listSection("Missing Evidence", review.missingEvidence),
    ...listSection(
      "Acceptance Checklist",
      review.acceptanceChecklist.map((item) => `${item.status}: ${item.criterion} - ${item.notes}`),
    ),
    ...listSection("Suggested Smoke Tests", review.suggestedSmokeTests),
    ...(review.verdict === "Needs Codex Fixes" && review.codexFixBrief
      ? [
          heading(3, "Draft Codex Fix Brief"),
          ...paragraph(review.codexFixBrief.summary),
          ...listSection("Fix Instructions", review.codexFixBrief.instructions),
          ...listSection("Verification", review.codexFixBrief.verification),
        ]
      : []),
    heading(3, "Evidence Captured"),
    ...paragraph(
      [
        `Changed files: ${evidence.pullRequest.changedFiles.map((file) => file.path).join(", ") || "None"}.`,
        `Checks: ${evidence.pullRequest.checks.map((check) => `${check.name}: ${check.conclusion ?? check.status}`).join(", ") || "None"}.`,
        `Deployments: ${evidence.pullRequest.deployments.length}.`,
        evidence.workOrder.prWorkOrderPath ? `Work order file: ${evidence.workOrder.prWorkOrderPath}.` : "Work order file: not found.",
      ].join(" "),
    ),
    heading(3, "Approval Boundary"),
    ...paragraph(
      "This review packet is evidence for Sherif. It does not merge, deploy, approve production, or dispatch Codex fixes automatically.",
    ),
  ];
}

export function renderPostMergeCloseoutBlocks(result: PostMergeCloseoutResult, generatedAt: Date): NotionAppendBlock[] {
  const pullRequest = result.evidence.pullRequest;
  const deployment = result.evidence.deployment;
  const propertyWrites = result.committed ? result.propertyWrites : result.plan.propertyWrites;
  const deploymentSummary =
    deployment.status === "found"
      ? deployment.deployments.map((item) => `${item.environment ?? "deployment"}: ${item.state ?? "unknown"}${item.url ? ` (${item.url})` : ""}`)
      : [deployment.message ?? "Deployment evidence not available."];

  return [
    { type: "divider", divider: {} },
    heading(2, `Post-Merge Closeout: ${pullRequest.repository}#${pullRequest.pullRequestNumber}`),
    ...paragraph(`Generated by chief-of-staff-agent-office Post-Merge Closeout at ${generatedAt.toISOString()}.`),
    heading(3, "Idempotency Marker"),
    ...paragraph(result.plan.closeoutMarker),
    heading(3, "Pull Request"),
    ...paragraph(`${pullRequest.title}: ${pullRequest.url}`),
    heading(3, "Selected Task PR Link Check"),
    ...paragraph(result.plan.taskPrLinkCheck.message),
    heading(3, "Merge Evidence"),
    ...paragraph(
      [
        `Merged at ${pullRequest.mergedAt}.`,
        `Merge SHA: ${pullRequest.mergeSha}.`,
        `Merged by: ${pullRequest.mergedBy ?? "unknown"}.`,
        `Branches: ${pullRequest.baseBranch} <- ${pullRequest.headBranch}.`,
      ].join(" "),
    ),
    ...listSection("Deployment Evidence", Array.isArray(deploymentSummary) ? deploymentSummary : [deploymentSummary]),
    ...listSection(
      "Notion Writes",
      propertyWrites.map((write) =>
        `${write.name}: ${write.status}${write.value !== undefined ? ` (${write.value})` : ""}${write.reason ? ` - ${write.reason}` : ""}`,
      ),
    ),
    heading(3, "Idempotency"),
    ...paragraph(
      result.committed
        ? result.blockAppended
          ? "Closeout block appended."
          : "Existing closeout marker found; block append skipped."
        : result.plan.markerAlreadyExists
          ? "Existing closeout marker found; commit will skip duplicate block append."
          : "No existing closeout marker found.",
    ),
    heading(3, "Approval Boundary"),
    ...paragraph(
      "Closeout records an already-merged PR. It does not merge, deploy, approve production, or dispatch Codex fixes automatically.",
    ),
  ];
}


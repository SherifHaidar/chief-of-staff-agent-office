export function chunkBlocks(blocks: NotionAppendBlock[], size = 100): NotionAppendBlock[][] {
  const chunks: NotionAppendBlock[][] = [];

  for (let index = 0; index < blocks.length; index += size) {
    chunks.push(blocks.slice(index, index + size));
  }

  return chunks;
}
